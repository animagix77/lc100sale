import assert from 'node:assert/strict';
import {DrivingMessages,readingSeconds} from './driving-messages.mjs';
const messages=new DrivingMessages(),long='Give yourself time to read this while keeping an eye on the trail. '.repeat(3);
assert.equal(readingSeconds('Range changed.'),30);
assert(readingSeconds(long)>30&&readingSeconds(long)<=45);
messages.say('Ease off the throttle before shifting.',0);
assert.equal(messages.say('Flag 02 reached.',2,{defer:true}),false);
assert.equal(messages.text,'Ease off the throttle before shifting.');
assert.equal(messages.update(29.9),false);
assert.equal(messages.update(30),true);assert.equal(messages.text,'Flag 02 reached.');
messages.say('Flag 03 reached.',32,{defer:true});messages.say('Flag 04 reached.',33,{defer:true});
messages.update(60);assert.equal(messages.text,'Flag 04 reached.','A burst of checkpoints does not build a stale message backlog');
messages.say('Flag 05 reached.',61,{defer:true});messages.say('Auto brake. Reverse or steer around.',62);
assert.equal(messages.pending,null,'Safety and direct-control feedback immediately replace the old context');
assert.equal(messages.update(100),false);
messages.say('Flag 06 reached.',101,{defer:true});messages.clear();assert.equal(messages.pending,null,'Reset discards stale announcements');
console.log('Driving messages: 30–45 second reading time, deferred checkpoints, bounded pending text, immediate control/safety feedback and reset passed');
