import assert from 'node:assert/strict';
import {AdaptiveQuality,StreamingBudget,readGraphicsMode,GRAPHICS_KEY} from './adaptive-quality.mjs';
const saved=new Map(),storage={getItem:k=>saved.get(k),setItem:(k,v)=>saved.set(k,v)};
const changes=[],quality=new AdaptiveQuality({mobile:true,pixelRatio:3,storage,onChange:(ratio,mode)=>changes.push({ratio,mode})});
const frames=(count,dt)=>{for(let i=0;i<count;i++)quality.sample(dt);};
frames(30,1/30);assert.equal(changes.length,0,'Brief slow work cannot change quality');
frames(180,1/30);assert.equal(changes.length,1,'Sustained missed frames lower resolution');
const ratio=quality.ratio;frames(240,1/60);assert.equal(quality.ratio,ratio,'Fast recovery must not oscillate tiers');
frames(1500,1/60);assert(quality.ratio>ratio);assert(quality.ratio<=1.2);
quality.setMode('detail');frames(1000,1/20);assert.equal(quality.ratio,1.2,'Explicit detail is stable');
quality.setMode('smooth');assert.equal(readGraphicsMode(storage),'smooth');assert.equal(saved.get(GRAPHICS_KEY),'smooth');
assert(quality.ratio<1.2);assert.equal(quality.setMode('garbage'),false);
assert.equal(readGraphicsMode({getItem(){throw Error('disabled')}}),'auto');
quality.setMode('auto');const beforeLong=quality.ratio;quality.sample(3);assert.equal(quality.ratio,beforeLong,'One isolated long frame cannot change quality');
frames(24,.5);assert(quality.ratio<beforeLong,'Sustained severe overload still reduces quality');quality.reset();assert.equal(quality.samples.length,0,'Pause resets observations');
let now=0;const budget=new StreamingBudget({milliseconds:4.5,clock:()=>now});budget.begin();
budget.run(3,ms=>{assert.equal(ms,3);now+=3.4;});
budget.run(2,ms=>{assert(Math.abs(ms-1.1)<1e-8);now+=2;});
assert.equal(budget.run(.9,()=>assert.fail('No work after an atomic overrun')),false);
now=100;budget.begin();assert.equal(budget.remaining(2),2);
console.log('Adaptive quality: sustained load, hysteresis, explicit modes, persistence and shared work allowance passed.');
